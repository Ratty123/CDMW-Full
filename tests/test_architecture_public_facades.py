class ArchitecturePublicFacadeTests(unittest.TestCase):
    def test_target_architecture_module_map_exists(self) -> None:
        missing = [path for path in TARGET_ARCHITECTURE_PATHS if not Path(path).exists()]
        self.assertEqual([], missing)

    def test_main_window_facade_exports_public_api(self) -> None:
        from cdmw.ui.main_window import MainWindow, mesh_import_mode_availability, run_gui

        self.assertTrue(callable(MainWindow))
        self.assertTrue(callable(mesh_import_mode_availability))
        self.assertTrue(callable(run_gui))

    def test_main_window_facade_does_not_import_app_window_directly(self) -> None:
        source = Path("cdmw/ui/main_window.py").read_text(encoding="utf-8")

        self.assertNotIn("cdmw.ui.shell.app_window", source)

    def test_legacy_feature_imports_still_resolve(self) -> None:
        from cdmw.ui.archive_browser_model import ArchiveBrowserModel
        from cdmw.ui.item_icons_tab import ItemIconLibraryTab
        from cdmw.ui.mesh_editor_tab import MeshEditorSessionRequest, MeshEditorTab
        from cdmw.ui.model_library_tab import ModelLibraryTab
        from cdmw.ui.research_tab import ResearchTab
        from cdmw.ui.text_search_tab import TextSearchTab

        for value in (
            ArchiveBrowserModel,
            ItemIconLibraryTab,
            MeshEditorSessionRequest,
            MeshEditorTab,
            ModelLibraryTab,
            ResearchTab,
            TextSearchTab,
        ):
            self.assertTrue(callable(value))

    def test_feature_packages_have_ownership_readmes(self) -> None:
        for path in FEATURE_PACKAGE_READMES:
            self.assertTrue(path.exists(), path)
            text = path.read_text(encoding="utf-8").strip()
            self.assertIn("Owns", text, path)


if __name__ == "__main__":
    unittest.main()
