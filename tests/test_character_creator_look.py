def test_reading_the_mod_folder_never_writes_it(tmp_path):
    game = tmp_path / "Crimson Desert"
    folder = game / "bin64" / "CharacterCreator"
    folder.mkdir(parents=True)
    (game / "bin64" / "CrimsonDesert.exe").write_bytes(b"MZ")
    assert creator_look.character_creator_folder(game) is None
    (folder / "data.version").write_text(VERSION, encoding="utf-8")
    (folder / "menu.txt").write_text(MENU, encoding="utf-8")
    (folder / "profile.txt").write_text(PROFILE, encoding="utf-8")
    assert creator_look.character_creator_folder(game) == folder
    assert creator_look.character_creator_folder("") is None
    stamps = {path.name: (path.stat().st_mtime_ns, path.read_bytes()) for path in folder.iterdir()}
    look = creator_look.read_kliff_look(folder)
    assert look.gender == 0 and look.parts[1].prefab == "cd_phw_00_head_00_0111"
    assert {path.name: (path.stat().st_mtime_ns, path.read_bytes()) for path in folder.iterdir()} == stamps
    (folder / "menu.txt").unlink()
    with pytest.raises(CharacterCreatorError, match="menu.txt is missing"):
        creator_look.read_kliff_look(folder)


