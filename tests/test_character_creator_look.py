class _Service(QObject):
    batch_ready = Signal(str, str, object)
    result_ready = Signal(str, str, object)
    request_failed = Signal(str, object)
    request_cancelled = Signal(str)

    def __init__(self):
        super().__init__()
        self.requests, self.cancelled = [], []

    def resolve_entries(self, request, *, ui_generation):
        self.requests.append(request)
        return f"lookup-{len(self.requests)}"

    def prepare_entries(self, request, *, ui_generation):
        self.requests.append(request)
        return f"prepare-{len(self.requests)}"

    def cancel(self, request):
        self.cancelled.append(request)


def _prepared(dto, path):
    return PrepareEntryResult(ArchiveEntryRef(dto.session_id, dto.entry_id, dto.identity, dto.path), str(path), 64, "sha")


def test_preparation_binds_each_part_to_its_own_prefab_descriptor(monkeypatch, tmp_path):
    look = resolve_kliff_look(VERSION, MENU, "mesh 1 201\n", "")
    models = {HEAD_PREFAB: (HEAD_PAC,), HAIR_PREFAB: (HAIR_PAC,)}
    monkeypatch.setattr(creator_look, "prefab_model_paths", lambda data: models[data.decode()])
    service = _Service()
    preparation = creator_look.KliffLookPreparation(service)
    ready, failed = [], []
    preparation.ready.connect(lambda *args: ready.append(args))
    preparation.failed.connect(lambda *args: failed.append(args))
    preparation.start("session-a", look, 7)

    lookup = service.requests[-1]
    assert lookup.kind is ArchiveLookupKind.BASENAMES
    assert "cd_phm_00_head_00_0008_macduff.prefab" in lookup.values
    assert "cd_phm_00_head_00_0008_macduff.prefabdata_xml" in lookup.values
    prefab, descriptor, hair = _dto(1, HEAD_PREFAB), _dto(2, HEAD_DESCRIPTOR), _dto(3, HAIR_PREFAB)
    # A shadowed copy of the same path is not the one the game loads.
    shadowed = _dto(9, HEAD_PREFAB, state="shadowed")
    service.batch_ready.emit("lookup-1", "resolve_entries", ArchiveLookupResult("session-a", (shadowed, prefab), 2, False))
    service.result_ready.emit("lookup-1", "resolve_entries", ArchiveLookupResult("session-a", (descriptor, hair), 2, False))
    assert service.requests[-1].entry_ids == (1, 2, 3)

    files = {}
    for dto, text in ((prefab, HEAD_PREFAB), (descriptor, DESCRIPTOR_XML), (hair, HAIR_PREFAB)):
        files[dto.entry_id] = tmp_path / f"{dto.entry_id}.bin"
        files[dto.entry_id].write_text(text, encoding="utf-8")
    service.result_ready.emit("prepare-2", "prepare_entries", PrepareEntriesResult(
        "session-a", tuple(_prepared(dto, files[dto.entry_id]) for dto in (prefab, descriptor, hair)), 3, 3, 192))
    paths = service.requests[-1]
    assert paths.kind is ArchiveLookupKind.EXACT_PATHS
    assert {HEAD_PAC, HEAD_PABC, HEAD_PAMT, HAIR_PAC} <= set(paths.values)

    pac, pabc, pamt, hair_pac = _dto(4, HEAD_PAC), _dto(5, HEAD_PABC), _dto(6, HEAD_PAMT), _dto(7, HAIR_PAC)
    service.result_ready.emit("lookup-3", "resolve_entries",
                              ArchiveLookupResult("session-a", (pac, pabc, pamt, hair_pac), 4, False))
    assert not failed
    token, detail, notes = ready[0]
    assert token == 7 and detail.row.key == KLIFF_LOOK_KEY
    head = next(component for component in detail.components if component.role == "head")
    assert head.name == "cd_phm_00_head_00_0008_macduff" and head.model_entry_ids == (4,)
    assert set(head.context_entry_ids) == {1, 2, 5, 6}
    # The body prefab is not in this archive: the part is skipped and named.
    assert [component.role for component in detail.components] == ["head", "hair"]
    assert notes == ("cd_phm_00_nude_01_0002_macduff.prefab is not in the loaded archives; that part is skipped.",)
    assert detail.total_file_count == len(detail.files) and not detail.truncated


def test_preparation_refuses_truncated_lookups_and_cancels_its_request():
    look = resolve_kliff_look(VERSION, MENU, "", "")
    service = _Service()
    preparation = creator_look.KliffLookPreparation(service)
    failed = []
    preparation.failed.connect(lambda token, message: failed.append((token, message)))
    preparation.start("session-a", look, 3)
    service.result_ready.emit("lookup-1", "resolve_entries", ArchiveLookupResult("session-a", (), 900, True))
    assert failed == [(3, "The archive lookup for the look's prefabs was cut short.")]
    preparation.start("session-a", look, 4)
    preparation.cancel()
    assert service.cancelled == ["lookup-2"]
    service.result_ready.emit("lookup-2", "resolve_entries", ArchiveLookupResult("session-a", (), 0, False))
    assert len(failed) == 1


def test_detail_lists_every_file_once_and_names_components_after_prefabs():
    part = CharacterCreatorPart(1, "cd_phm_00_head_00_0008_macduff", 201)
    resolved = CharacterCreatorResolvedPart(part, _dto(1, HEAD_PREFAB), _dto(2, HEAD_DESCRIPTOR),
                                            (_dto(4, HEAD_PAC),), (_dto(5, HEAD_PABC),))
    detail = kliff_look_detail("session-a", (resolved,))
    assert [(file.entry_id, file.relation) for file in detail.files] == [
        (1, "prefab"), (2, "descriptor"), (5, "descriptor_reference"), (4, "model")]
    assert [model.entry_id for model in detail.models] == [4]
    assert detail.components[0].name == part.prefab and detail.components[0].context_entry_ids == (1, 2, 5)
