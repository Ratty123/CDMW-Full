def test_unknown_versions_options_and_identities_are_refused_with_their_reason():
    with pytest.raises(UnsupportedCharacterCreatorVersion) as refused:
        resolve_kliff_look("9.2.0 1 2\n", MENU, PROFILE, "")
    assert refused.value.version == "9.2.0" and "9.1.16" in str(refused.value)
    with pytest.raises(CharacterCreatorError, match="Head option 98"):
        resolve_kliff_look(VERSION, MENU, "mesh 1 98\n", "")
    with pytest.raises(CharacterCreatorError, match="no base look for a female dwarf"):
        resolve_kliff_look(VERSION, MENU, "", "1 2 0 0")
    with pytest.raises(CharacterCreatorError, match="gender 2"):
        resolve_kliff_look(VERSION, MENU, "", "2 0 0 0")
    with pytest.raises(CharacterCreatorError, match="profile.txt line 1"):
        resolve_kliff_look(VERSION, MENU, "hair 3\n", "")


