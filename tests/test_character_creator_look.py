def test_kliff_look_maps_stored_options_through_the_kliff_column():
    look = resolve_kliff_look(VERSION, MENU, PROFILE, "1 0 12 1\n")
    assert [(part.label, part.option, part.prefab) for part in look.parts] == [
        ("Body", 11, "cd_phw_00_nude_00_0001_damian"),
        ("Head", 99, "cd_phw_00_head_00_0111"),
        ("Hair", 14, "cd_phm_00_hair_00_0003"),
        ("Beard", 5, "cd_phm_00_beard_00_0009_04_player"),
    ]
    assert (look.gender, look.race, look.height_percent, look.head_scale) == (1, 0, 12.0, 1.02)
    assert look.scaled_body == pytest.approx(0.94 * 1.12)
    assert look.face_details == "cd_phw_00_head_00_0111" and look.decoration_count == 2


