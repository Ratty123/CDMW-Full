from __future__ import annotations

import re
from pathlib import Path

from cdmw.constants import APP_NAME, APP_ORGANIZATION, APP_REPOSITORY_URL, APP_TITLE, APP_VERSION


def windows_file_version_tuple(version: str = APP_VERSION) -> tuple[int, int, int, int]:
    """Return the four 16-bit integers required by Windows VERSIONINFO."""
    values = [int(part) for part in re.findall(r"\d+", version)]
    values = (values + [0, 0, 0, 0])[:4]
    return tuple(min(max(value, 0), 65535) for value in values)


def windows_version_resource_text(version: str = APP_VERSION) -> str:
    filevers = windows_file_version_tuple(version)
    product_name = APP_TITLE
    original_filename = f"{APP_NAME}.exe"
    return f"""# UTF-8
#
# Generated by cdmw.build_metadata. This gives unsigned PyInstaller builds
# normal publisher/product metadata for Windows reputation and diagnostics.

VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={filevers!r},
    prodvers={filevers!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
    ),
  kids=[
    StringFileInfo(
      [
      StringTable(
        '040904B0',
        [
        StringStruct('CompanyName', {APP_ORGANIZATION!r}),
        StringStruct('FileDescription', {APP_TITLE!r}),
        StringStruct('FileVersion', {version!r}),
        StringStruct('InternalName', {APP_NAME!r}),
        StringStruct('OriginalFilename', {original_filename!r}),
        StringStruct('ProductName', {product_name!r}),
        StringStruct('ProductVersion', {version!r}),
        StringStruct('Comments', {'Official repository: ' + APP_REPOSITORY_URL!r})
        ])
      ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_windows_version_resource(path: Path, version: str = APP_VERSION) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(windows_version_resource_text(version), encoding="utf-8")
    return path
