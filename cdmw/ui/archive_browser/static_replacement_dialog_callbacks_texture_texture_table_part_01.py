def _texture_texture_table_step_013(_state):

    def _refresh_texture_row_in_place(row_state: Dict[str, Any], *, sync_editor: bool=True) -> bool:
        item = _state.texture_override_tree.currentItem()
        if item is None or item.data(0, _state.Qt.UserRole + 1) is not row_state:
            item = _state._texture_item_for_row_helper(_state.texture_override_tree, row_state)
        if item is None:
            return False
        _state.selected_texture_row['row'] = row_state
        _state.texture_override_tree.blockSignals(True)
        try:
            _state.texture_override_tree.setCurrentItem(item)
            _state._apply_texture_row_to_item(item, row_state)
        finally:
            _state.texture_override_tree.blockSignals(False)
        _state._update_texture_summary_label()
        _state._refresh_texture_details(row_state, sync_editor=sync_editor)
        _state.texture_override_tree.scrollToItem(item, _state.QAbstractItemView.EnsureVisible)
        return True
    _state._refresh_texture_row_in_place = _refresh_texture_row_in_place

def _texture_texture_table_step_014(_state):

    def _refresh_texture_table(preserve_row: Optional[Dict[str, Any]]=None, *, select_first: bool=False) -> None:
        if preserve_row is None:
            preserve_row = _state.selected_texture_row.get('row')
        previous_scroll_value = _state.texture_override_tree.verticalScrollBar().value()
        _state.texture_busy_bar.setFormat('Updating texture assignments...')
        _state.texture_busy_bar.setVisible(True)
        _state.texture_override_tree.blockSignals(True)
        try:
            _state._refresh_alignment_virtual_sidecar_contract(_state._current_dialog_mappings_for_preview())
            _state.texture_override_tree.clear()
            visible_rows = [row_state for row_state in sorted(_state.texture_override_rows, key=lambda row_state: _state._texture_override_row_sort_key(row_state, _state.texture_rows_by_target, assigned_predicate=_state.texture_row_assigned)) if _state._texture_row_visible_helper(row_state, show_advanced=bool(_state.texture_show_advanced_checkbox.isChecked()), filter_selected=bool(_state.texture_filter_selected_checkbox.isChecked()), selected_source_index=int(_state.selected_source_part.get('index', -1)))]
            _state._update_texture_summary_label(len(visible_rows))
            item_to_select: _state.Optional[_state.QTreeWidgetItem] = None
            for row_state in visible_rows:
                item = _state._texture_override_item_helper()
                _state._apply_texture_row_to_item(item, row_state)
                _state.texture_override_tree.addTopLevelItem(item)
                if preserve_row is row_state:
                    item_to_select = item
            _state.texture_override_tree.blockSignals(False)
            if item_to_select is not None:
                _state.texture_override_tree.setCurrentItem(item_to_select)
                _state.selected_texture_row['row'] = item_to_select.data(0, _state.Qt.UserRole + 1)
                _state.texture_override_tree.scrollToItem(item_to_select, _state.QAbstractItemView.EnsureVisible)
            else:
                _state.selected_texture_row['row'] = None
                _state.texture_override_tree.clearSelection()
                _state.texture_override_tree.setCurrentIndex(_state.QModelIndex())
                _state.texture_override_tree.verticalScrollBar().setValue(previous_scroll_value)
            _state._refresh_texture_details(_state.selected_texture_row.get('row'))
            _state.texture_override_tree.setMinimumHeight(320)
            _state.texture_override_tree.setMaximumHeight(16777215)
            _state._auto_fit_alignment_tree_columns(_state.texture_override_tree, (120, 150, 90, 180, 220, 96, 180), (220, 280, 180, 340, 420, 140, 360), expand_column=4)
        finally:
            _state.texture_override_tree.blockSignals(False)
            _state.texture_busy_bar.setVisible(False)
    _state._refresh_texture_table = _refresh_texture_table

